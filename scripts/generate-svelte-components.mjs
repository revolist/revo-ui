import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const catalog = read('package/component-catalog.ts');
const names = [...catalog.matchAll(/^  (\w+): (?:ui\.)?\w+,/gm)].map(
  (match) => match[1],
);
const modelsSource = ts.createSourceFile(
  'metadata.ts',
  read('package/component-metadata.ts'),
  ts.ScriptTarget.Latest,
  true,
);
const models = new Map();
for (const statement of modelsSource.statements) {
  if (!ts.isVariableStatement(statement)) continue;
  for (const declaration of statement.declarationList.declarations) {
    if (
      declaration.name.getText() !== 'componentModels' ||
      !declaration.initializer
    )
      continue;
    for (const property of declaration.initializer.properties) {
      const values = Object.fromEntries(
        property.initializer.properties.map((entry) => [
          entry.name.getText(),
          entry.initializer.text,
        ]),
      );
      models.set(property.name.getText(), values);
    }
  }
}
let stale = false;
function output(path, content) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    let current;
    try {
      current = readFileSync(target, 'utf8');
    } catch {}
    if (current !== content) {
      console.error(`Outdated: ${fileURLToPath(target)}`);
      stale = true;
    }
  } else writeFileSync(target, content);
}
output(
  'package/svelte-adapter.models.ts',
  `// Generated by scripts/generate-svelte-components.mjs.\nexport interface SvelteModelCallbacks {\n${[...models].map(([name, model]) => `  ${name}: '${model.callback}';`).join('\n')}\n}\n`,
);
const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
for (const name of names) {
  const model = models.get(name);
  const controlImport = `import { ${name} as Control } from '../component-controls/${kebab(name)}';`;
  const binding = model ? `, ${model.prop} = $bindable()` : '';
  const nativeProps = model
    ? `{ ...props, ${model.prop}, ${model.callback}: updateModel }`
    : 'props';
  const handler = model
    ? `
  function updateModel(...args: Parameters<NonNullable<UiComponentProps<'${name}'>['${model.callback}']>>) {
    ${model.prop} = args[0];
    if (props.${model.callback}) return Reflect.apply(props.${model.callback}, undefined, args);
  }
`
    : '';
  output(
    `package/svelte/${name}.svelte`,
    `<!-- Generated by scripts/generate-svelte-components.mjs. -->
<script lang="ts">
  ${controlImport}
  import Mount from './Mount.svelte';
  import type { SvelteComponentProps } from '../svelte-props';
${model ? "  import type { UiComponentProps } from '../component-catalog';\n" : ''}
  let { children, slots, onUiEvent${binding}, ...props }: SvelteComponentProps<'${name}'> = $props();
  let mount: Mount;
${handler}
  export function getElement(): HTMLElement | null {
    return mount?.getElement() ?? null;
  }
</script>

<Mount
  bind:this={mount}
  component="${name}"
  control={Control}
  direct
  props={${nativeProps}}
  {children}
  {slots}
  {onUiEvent}
/>
`,
  );
  output(
    `package/svelte/${name}.svelte.d.ts`,
    `// Generated by scripts/generate-svelte-components.mjs.
import type { Component } from 'svelte';
import type { SvelteComponentProps, SvelteUiHandle } from '../svelte-props';
declare const ${name}: Component<SvelteComponentProps<'${name}'>, SvelteUiHandle, '${model?.prop ?? ''}'>;
export default ${name};
`,
  );
}
const marker =
  '// Named adapters generated by scripts/generate-svelte-components.mjs.\n';
const current = read('package/svelte.ts').split(marker)[0];
output(
  'package/svelte.ts',
  current +
    marker +
    names
      .map(
        (name) =>
          `export { default as ${name} } from './svelte/${name}.svelte';`,
      )
      .join('\n') +
    '\n',
);
if (stale) process.exitCode = 1;
else
  console.log(
    `${names.length} named Svelte adapters ${process.argv.includes('--check') ? 'checked' : 'generated'}.`,
  );
