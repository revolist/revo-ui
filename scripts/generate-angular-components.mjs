import ts from "typescript";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { componentApi } from "./component-api.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "package/angular-components");
const catalog = readFileSync(
  resolve(root, "package/component-catalog.ts"),
  "utf8",
);
const names = [...catalog.matchAll(/^  (\w+):/gm)].map((match) => match[1]);
const api = new Map(
  componentApi(root, root).map((component) => [component.name, component]),
);
const metadata = ts.createSourceFile(
  "component-metadata.ts",
  readFileSync(resolve(root, "package/component-metadata.ts"), "utf8"),
  ts.ScriptTarget.Latest,
  true,
);
const models = new Map();
for (const statement of metadata.statements) {
  if (!ts.isVariableStatement(statement)) continue;
  for (const declaration of statement.declarationList.declarations) {
    if (declaration.name.getText(metadata) !== "componentModels") continue;
    for (const entry of declaration.initializer.properties) {
      const props = Object.fromEntries(
        entry.initializer.properties.map((prop) => [
          prop.name.getText(metadata),
          prop.initializer.text,
        ]),
      );
      models.set(entry.name.getText(metadata), props);
    }
  }
}
const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
const generated = new Map();
for (const name of names) {
  const component = api.get(name);
  const model = models.get(name);
  const inputs = [...component.props, ...component.events].filter(
    (prop) => !["children", "ref", "key", "jsx"].includes(prop.name),
  );
  const events = component.events.filter(
    (event) => event.name !== model?.callback,
  );
  // Native DOM names remain native events; callback outputs use an Event suffix
  // so Angular does not subscribe to both a bubbling event and the same output.
  const eventName = (event) => {
    const plain = event.name.slice(2, 3).toLowerCase() + event.name.slice(3);
    return event.inherited ||
      [
        "click",
        "change",
        "input",
        "focus",
        "blur",
        "submit",
        "reset",
        "close",
        "select",
        "scroll",
        "toggle",
        "load",
        "error",
      ].includes(plain)
      ? `${plain}Event`
      : plain;
  };
  const eventNames = new Set();
  const outputs = events.filter((event) => {
    const alias = eventName(event);
    if (
      alias === "valueChange" ||
      alias === "uiEvent" ||
      inputs.some((input) => input.name === alias) ||
      eventNames.has(alias)
    )
      return false;
    eventNames.add(alias);
    return true;
  });
  const header = `// Generated by scripts/generate-angular-components.mjs. Do not edit.\nimport { Component, Input as NgInput, Output } from '@angular/core';\nimport { ${name} as Control } from '../component-controls/${kebab(name)}';\nimport { AngularComponentAdapter, type AngularInput, type AngularCallbackValue } from '../angular-adapter';\n\n@Component({\n  selector: 'rv-${kebab(name)}',\n  standalone: true,\n  template: '<span #rvHost style="display: contents"></span><span #rvProjected style="display: none"><ng-content /></span>',\n  host: { style: 'display: contents', ngSkipHydration: 'true' },\n})\nexport class ${name} extends AngularComponentAdapter<${model ? `AngularCallbackValue<AngularInput<'${name}', '${model.callback}'>>` : "never"}> {\n  protected readonly rvComponentName = '${name}';\n  protected rvResolveComponent() { return Control; }\n`;
  const requiredCallbacks = component.events
    .filter((event) => event.required)
    .map((event) => event.name);
  const callbackDefaults = requiredCallbacks.length
    ? `  protected override readonly rvRequiredCallbacks = ${JSON.stringify(requiredCallbacks)};\n`
    : "";
  const requiresInput = (prop) =>
    prop.required &&
    !/^on[A-Z]/.test(prop.name) &&
    !/ComponentChildren|VNode/.test(prop.type);
  const fields = inputs
    .map(
      (prop) =>
        `  @NgInput(${requiresInput(prop) ? "{ required: true }" : ""}) declare ${JSON.stringify(prop.name)}${requiresInput(prop) ? "" : "?"}: AngularInput<'${name}', ${JSON.stringify(prop.name)}>;`,
    )
    .join("\n");
  const callbackFields = outputs
    .map(
      (event) =>
        `  @Output() get ${eventName(event)}() { return this.rvOutput<AngularCallbackValue<AngularInput<'${name}', '${event.name}'>>>('${event.name}'); }`,
    )
    .join("\n");
  const modelField =
    model && model.prop !== "value"
      ? `  @Output() get ${model.prop}Change() { return this.rvOutput<AngularCallbackValue<AngularInput<'${name}', '${model.callback}'>>>('${model.callback}'); }`
      : "";
  const outputFields = [callbackFields, modelField].filter(Boolean).join("\n");
  const readProps = `\n  protected rvResolveProps() { return this.rvInputValues; }\n`;
  const outputMap = "";
  generated.set(
    `${kebab(name)}.ts`,
    header +
      callbackDefaults +
      fields +
      "\n" +
      outputFields +
      readProps +
      outputMap +
      "}\n",
  );
}
generated.set(
  "index.ts",
  "// Generated by scripts/generate-angular-components.mjs. Do not edit.\n" +
    names
      .map((name) => `export { ${name} } from './${kebab(name)}';`)
      .join("\n") +
    "\n",
);
mkdirSync(output, { recursive: true });
for (const [name, source] of generated) {
  const path = resolve(output, name);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== source)
      throw new Error(`Outdated Angular adapter: ${name}`);
  } else writeFileSync(path, source);
}
console.log(
  `${process.argv.includes("--check") ? "Checked" : "Generated"} ${names.length} named Angular components`,
);
