import { formatGenerated } from './generated-format.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { componentControls } from './generate-component-controls.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const file = new URL('../package.json', import.meta.url);
const current = readFileSync(file, 'utf8');
const manifest = JSON.parse(current);
for (const key of Object.keys(manifest.exports)) {
  if (key.startsWith('./angular/') || key.startsWith('./svelte/'))
    delete manifest.exports[key];
}
for (const { name, slug } of componentControls(root)) {
  manifest.exports[`./angular/${slug}`] =
    `./package/angular-components/${slug}.ts`;
  manifest.exports[`./svelte/${slug}`] = `./package/svelte-entries/${slug}.ts`;
  const entry = new URL(
    `../package/svelte-entries/${slug}.ts`,
    import.meta.url,
  );
  const contents = await formatGenerated(
    `// Generated by scripts/generate-framework-exports.mjs.\nexport { default, default as ${name} } from '../svelte/${name}.svelte';\n`,
    `${slug}.ts`,
  );
  if (process.argv.includes('--check')) {
    if (readFileSync(entry, 'utf8') !== contents)
      throw new Error(`Stale Svelte entry: ${slug}`);
  } else {
    mkdirSync(new URL('../package/svelte-entries/', import.meta.url), {
      recursive: true,
    });
    writeFileSync(entry, contents);
  }
}
const next = `${JSON.stringify(manifest, null, 2)}\n`;
if (process.argv.includes('--check')) {
  if (current !== next)
    throw new Error('Run node scripts/generate-framework-exports.mjs');
} else writeFileSync(file, next);
