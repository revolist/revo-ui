export type AiUiTranslations = Partial<
  Record<(typeof AI_UI_MESSAGES)[number], string>
>;
export function translateAiText(
  text: string,
  translations: Readonly<Record<string, string | undefined>> = {},
  values: Readonly<Record<string, string | number>> = {},
): string {
  return (translations[text] ?? text).replace(
    /\{(\w+)\}/g,
    (token, key: string) =>
      Object.hasOwn(values, key) ? String(values[key]) : token,
  );
}
