import type { ComponentChildren, JSX } from 'preact';
export type TooltipAnchor = HTMLElement | SVGElement;
export type TooltipSide =
  | 'top'
  | 'bottom'
  | 'left'
  | 'right'
  | 'inline-start'
  | 'inline-end';
export type TooltipAlign = 'start' | 'center' | 'end';
export type TooltipReason =
  | 'hover'
  | 'focus'
  | 'click'
  | 'imperative'
  | 'controlled'
  | 'escape'
  | 'outside-press'
  | 'pointer-leave'
  | 'blur'
  | 'press'
  | 'disabled'
  | 'owner-change'
  | 'anchor-removed'
  | 'viewport'
  | 'destroy';
export interface TooltipChangeDetails {
  reason: TooltipReason;
  target: TooltipAnchor;
  event?: Event;
}
export interface TooltipContentContext extends TooltipChangeDetails {
  signal: AbortSignal;
}
export type TooltipContent = ComponentChildren | Node;
export interface TooltipOffsetContext {
  anchor: DOMRect;
  popup: DOMRect;
  side: Exclude<TooltipSide, 'inline-start' | 'inline-end'>;
  align: TooltipAlign;
}
export type TooltipOffset =
  | number
  | ((context: TooltipOffsetContext) => number);
export interface TooltipPositionOptions {
  /** Preferred side; defaults to top. Logical sides follow direction. */
  side?: TooltipSide;
  /** Backward-compatible alias for side="top". */
  placement?: 'above';
  /** Cross-axis alignment; defaults to center. */
  align?: TooltipAlign;
  /** Distance from the trigger in pixels; defaults to 8. */
  sideOffset?: TooltipOffset;
  /** Cross-axis displacement in pixels; defaults to 0. */
  alignOffset?: TooltipOffset;
  /** Override the computed direction of the trigger. */
  direction?: 'ltr' | 'rtl';
  /** Boundary intersected with the viewport; viewport by default. */
  collisionBoundary?: Element | DOMRect;
  /** Inset from each boundary edge; defaults to 8px per unspecified edge. */
  collisionPadding?:
    | number
    | Partial<Record<'top' | 'bottom' | 'left' | 'right', number>>;
  /** Flip and shift by default; false disables collision handling. */
  collisionAvoidance?:
    | boolean
    | { side?: 'flip' | 'none'; align?: 'shift' | 'none' };
  /** Follow scrolling triggers even without keyboard focus. */
  sticky?: boolean;
}
export interface TooltipGroupOptions {
  /** Hover delay in milliseconds; groups default to 600, individual tooltips to 0. */
  delay?: number;
  /** Pointer-exit delay in milliseconds; defaults to 0. */
  closeDelay?: number;
  /** Warm window after closing in milliseconds; defaults to 400. */
  skipDelayDuration?: number;
}
/** Explicitly shared across framework roots; no renderer-specific context required. */
export class TooltipGroup {
  private active = new Set<object>();
  private warmUntil = 0;
  constructor(public options: TooltipGroupOptions = {}) {}
  getDelay() {
    return this.active.size || Date.now() < this.warmUntil
      ? 0
      : Math.max(0, this.options.delay ?? 600);
  }
  opened(owner: object) {
    this.active.add(owner);
  }
  closed(owner: object) {
    if (this.active.delete(owner))
      this.warmUntil =
        Date.now() + Math.max(0, this.options.skipDelayDuration ?? 400);
  }
}
export const createTooltipGroup = (options?: TooltipGroupOptions) =>
  new TooltipGroup(options);
export interface TooltipOptions extends TooltipPositionOptions {
  /** Stable description ID; generated by default. */
  id?: string;
  /** Hover includes focus by default; arrays select explicit modes. */
  trigger?:
    | 'hover'
    | 'focus'
    | 'click'
    | 'manual'
    | readonly ('hover' | 'focus' | 'click')[];
  /** Delegate to matching descendants. Hover/focus on child nodes resolves to their matching trigger. */
  filter?: string;
  /** Suppress the tooltip without disabling the trigger. */
  disabled?: boolean;
  /** Controlled visibility. Interaction requests notify onOpenChange; the supplied value authorizes visibility. */
  open?: boolean;
  /** Hover delay in milliseconds; groups default to 600, individual tooltips to 0. */
  delay?: number;
  /** Pointer-exit delay in milliseconds; defaults to 0. */
  closeDelay?: number;
  /** Keyboard-focus delay in milliseconds; defaults to 0. */
  focusDelay?: number;
  /** Shared warm-up timing across separate tooltip/framework roots. */
  group?: TooltipGroup;
  /** Dismiss on pointer exit; defaults to true. */
  autoHide?: boolean;
  /** Disable the hover bridge to the popup; defaults to false. */
  disableHoverablePopup?: boolean;
  /** Allow Escape dismissal; defaults to true. */
  closeOnEscape?: boolean;
  /** Allow outside-pointer dismissal; defaults to true. */
  closeOnOutside?: boolean;
  /** Dismiss ordinary hints on activation; defaults to true. */
  hideOnClick?: boolean;
  /** Portal destination; detached surfaces mount in the trigger document body. */
  appendTo?: HTMLElement | ShadowRoot;
  /** Retain the hidden surface after opening; destroy still disposes it. */
  keepMounted?: boolean;
  /** Show a decorative positioning arrow; defaults to false. */
  arrow?: boolean;
  /** Popup width: pixels or a CSS length. */
  width?: number | string;
  /** Popup height: pixels or a CSS length. */
  height?: number | string;
  /** Maximum width; defaults to 360px constrained by the viewport. */
  maxWidth?: number | string;
  /** Maximum height; defaults to the viewport minus 16px. */
  maxHeight?: number | string;
  /** Additional surface classes. */
  className?: string;
  /** Additional inline surface styles and theme variables. */
  style?: JSX.CSSProperties;
  /** Zero by default. Shared reduced-motion settings override this duration. */
  transitionDuration?: number;
  /** Return false to cancel an interaction request. Forced cleanup bypasses cancellation. */
  onBeforeOpenChange?: (
    open: boolean,
    details: TooltipChangeDetails,
  ) => boolean | void;
  /** Visibility request with its trigger, reason and originating event. */
  onOpenChange?: (open: boolean, details: TooltipChangeDetails) => void;
  /** Actual visibility completion after motion, or immediately without it. */
  onOpenChangeComplete?: (open: boolean, details: TooltipChangeDetails) => void;
  /** Runs when the popup logically opens. */
  onShow?: (details: TooltipChangeDetails) => void;
  /** Runs when the popup logically closes; destruction silently cleans up. */
  onHide?: (details: TooltipChangeDetails) => void;
  /** Runs when an active or pending popup handles Escape. */
  onEscape?: () => void;
}
export interface TooltipControllerOptions extends TooltipOptions {
  /** Optional caller-supplied presentation element. */
  surface?: HTMLElement;
  /** Render descriptive content for the active trigger. */
  renderContent?: (context: TooltipChangeDetails) => TooltipContent;
  /** Async text stays text; the host owns fetching, authentication and error wording. */
  loadContent?: (context: TooltipContentContext) => Promise<string>;
  /** Caller-translated content shown while loading. */
  loadingContent?: TooltipContent;
  /** Caller-translated load failure content; omitted failures dismiss the popup. */
  errorContent?: TooltipContent;
  /** Current asynchronous content loaded successfully. */
  onContentLoad?: (content: string, details: TooltipChangeDetails) => void;
  /** Current asynchronous content failed to load; canceled/stale failures are ignored. */
  onError?: (error: unknown, details: TooltipChangeDetails) => void;
}
