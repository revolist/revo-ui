/** Generate Sass from the same pure data modules consumed by products and the gallery. */
import { readFile, writeFile } from 'node:fs/promises';
import { tsImport } from 'tsx/esm/api';
const { builtInColorPalettes } = await tsImport(
  '../src/color-palette/built-in-palettes.ts',
  import.meta.url,
);
const ids = new Set();
const quote = (value) => JSON.stringify(value);
const palettes = builtInColorPalettes.map((palette) => {
  if (ids.has(palette.id)) throw new Error(`Duplicate palette: ${palette.id}`);
  ids.add(palette.id);
  const entries = Object.entries(palette.colors).map(([key, value]) => {
    if (typeof value !== 'string' || !value.trim())
      throw new Error(`Invalid color: ${palette.id}/${key}`);
    return `    ${quote(key)}: ${quote(value)},`;
  });
  return `  ${quote(palette.id)}: (\n${entries.join('\n')}\n  ),`;
});
const output = `// Generated by scripts/generate-palettes.mjs. Edit the named TypeScript palettes instead.\n@use 'sass:map';\n@use 'sass:string';\n$palettes: (\n${palettes.join('\n')}\n);\n\n@function color($palette, $name) {\n  $values: map.get($palettes, $palette);\n  @if $values == null or not map.has-key($values, $name) {\n    @error 'Unknown built-in palette color: #{$palette}/#{$name}';\n  }\n  @return string.unquote(map.get($values, $name));\n}\n\n@function uri-color($palette, $name) {\n  $value: color($palette, $name);\n  @if string.slice($value, 1, 1) != '#' {\n    @error 'URI color must be hexadecimal: #{$palette}/#{$name}';\n  }\n  @return string.unquote('%23' + string.slice($value, 2));\n}\n`;
const target = new URL(
  '../src/styles/_built-in-palettes.scss',
  import.meta.url,
);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== output) {
    console.error(
      'Built-in Sass palettes are stale. Run pnpm --filter @revolist/ui generate:palettes.',
    );
    process.exitCode = 1;
  }
} else await writeFile(target, output);
